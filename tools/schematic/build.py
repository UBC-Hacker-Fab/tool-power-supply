import sys,os,shutil
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
import design
from design import *
OUT=sys.argv[1] if len(sys.argv)>1 else os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','tool-power-supply-v1')
os.makedirs(OUT,exist_ok=True)
# refs
cnt={}
for n in ORDER:
    for title,comps in sheets[n].sections:
        for c in comps:
            pre=c.prefix
            cnt[pre]=cnt.get(pre,0)+1
            c.ref=(f'{pre}{cnt[pre]:02d}' if pre.startswith('#') else f'{pre}{cnt[pre]}')
# layout + emit
papers={}
for n in ORDER:
    sh=sheets[n]
    pname,W,H=layout(sh); papers[n]=pname
    path=f'/{root_uuid}/{sh.uuid}'
    tree=emit_sheet(sh,pname,W,H,None,path)
    fn=f'{OUT}/{n}.kicad_sch'
    open(fn,'w').write(dump(tree)+'\n')
    print(n,pname,sum(len(c) for _,c in sh.sections),'components')
