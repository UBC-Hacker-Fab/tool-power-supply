def U(): return str(uuid.uuid4())
def fmt(v):
    v=round(v,4)
    if abs(v-round(v))<1e-9: return str(int(round(v)))
    return ('%.4f'%v).rstrip('0').rstrip('.')
def font(size=1.27,hide=False,justify=None,bold=False):
    e=['effects',['font',['size',fmt(size),fmt(size)]]]
    if justify: e.append(['justify']+justify.split())
    if hide: e.append(['hide','yes'])
    return e
def rot_vec(x,y,rot):
    rot%=360
    if rot==0: return (x,y)
    if rot==90: return (-y,x)
    if rot==180: return (-x,-y)
    if rot==270: return (y,-x)
    raise ValueError(rot)

class Comp:
    def __init__(s,lib,value,pins,fp=None,ref=None,prefix=None,rot=None,props=None,dnp=False,on_board=True,section=None,note=None,desc=None,unit=1):
        s.lib=lib; s.value=value; s.pinmap=pins; s.fp=fp; s.ref=ref; s.prefix=prefix; s.rot=rot
        s.props=props or {}; s.dnp=dnp; s.on_board=on_board; s.note=note; s.desc=desc; s.unit=unit
        s.nick,s.name=lib.split(':')
        s.pins=[p for p in pins_of(s.nick,s.name) if p['unit'] in (0,unit) and p['style'] in (0,1)]
        if s.rot is None:
            angs=[p['a'] for p in s.pins]
            s.rot=90 if (len(s.pins)==2 and all(a in (90,270) for a in angs)) else 0
        s.uuid=U()

_pc={}
def pins_of(nick,name):
    k=(nick,name)
    if k not in _pc: _pc[k]=pins(nick,name)
    return _pc[k]

def text_w(t): return 1.2*len(t)+3
STUB=5.08

def comp_extent(c):
    """bbox in schematic offsets relative to origin, including stubs and labels"""
    xs=[0];ys=[0]
    s=flatten(c.nick,c.name)
    def walk(x):
        if isinstance(x,list):
            if x and x[0] in ('start','end','xy','center') and len(x)>=3:
                try:
                    px,py=float(x[1]),float(x[2]); X,Y=rot_vec(px,py,c.rot); xs.append(X);ys.append(-Y)
                except: pass
            for z in x: walk(z)
    walk(s)
    for p in c.pins:
        X,Y=rot_vec(p['x'],p['y'],c.rot); xs.append(X); ys.append(-Y)
        net=c.pinmap.get(p['number'])
        if net is None or net=='NC':
            ox,oy=out_dir(p,c.rot); xs.append(X+ox*STUB); ys.append(-Y+oy*STUB); continue
        ox,oy=out_dir(p,c.rot); L=STUB+text_w(net)
        xs.append(X+ox*L); ys.append(-Y+oy*L)
    return min(xs),min(ys),max(xs),max(ys)

def out_dir(p,rot):
    a=math.radians(p['a'])
    ox,oy=-round(math.cos(a)),-round(math.sin(a))   # symbol space outward (inward is angle)
    X,Y=rot_vec(ox,oy,rot)
    return (X,-Y)   # schematic

def label_angle(d):
    return {(1,0):0,(0,-1):90,(-1,0):180,(0,1):270}[d]

