PAPERS=[('A3',420,297),('A2',594,420),('A1',841,594),('A0',1189,841)]
def snap(v,g=2.54): return round(round(v/g)*g,4)

def layout(sheet):
    """returns paper name and sets c.x,c.y"""
    for pname,W,H in PAPERS:
        res=try_layout(sheet,W,H)
        if res: return pname,W,H
    raise RuntimeError('does not fit in A0: '+sheet.name)
def try_layout(sheet,W,H):
    mx=15; top=30; gap=6
    y=top; ok=True
    sheet.sect_pos=[]
    for title,comps in sheet.sections:
        sheet.sect_pos.append((title,mx,y)); y+=10
        x=mx; rowh=0; row_y=y
        for c in comps:
            x0,y0,x1,y1=comp_extent(c)
            w=x1-x0+gap; h=y1-y0+gap+4
            if x+w>W-mx and x>mx:
                x=mx; row_y+=rowh; rowh=0
            c.x=snap(x-x0+gap/2); c.y=snap(row_y-y0+gap/2+6)
            x+=w; rowh=max(rowh,h)
        y=row_y+rowh+6
    return y<H-20

def emit_sheet(sheet,paper,W,H,refcounter,sheet_path,out_net_pwrflags=()):
    kids=[]
    kids+= [['version','20260306'],['generator',Q('eeschema')],['generator_version',Q('10.0')],['uuid',Q(sheet.uuid)],['paper',Q(paper)]]
