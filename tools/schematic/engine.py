def lib_symbol_entry(nick,name):
    s=copy.deepcopy(flatten(nick,name))
    s[1]=Q(f'{nick}:{name}')
    # drop extends (already flattened) 
    s=[x for x in s if not (isinstance(x,list) and x and x[0]=='extends')]
    return s

def emit_comp(c,sheet,path):
    out=[]
    x,y,rot=c.x,c.y,c.rot
    ref=c.ref
    # property placement
    x0,y0,x1,y1=comp_extent_noLabels(c)
    horiz=all(out_dir(p,c.rot)[1]==0 for p in c.pins)
    pang=(-c.rot)%360
    def P(name,val,px,py,hide=False,just=None,ang=None):
        pr=['property',Q(name),Q(val),['at',fmt(px),fmt(py),str(pang if ang is None else ang)],['effects',['font',['size','1.27','1.27']]]]
        if just: pr[4].append(['justify']+just.split())
        if hide: pr[4].append(['hide','yes'])
        return pr
    if horiz and len(c.pins)<=3:
        rpos=(x,y+y0-1.6,None); vpos=(x,y+y1+1.6,None)
    else:
        rpos=(x+x0,y+y0-4.8,'left'); vpos=(x+x0,y+y0-1.6,'left')
    inst=['symbol',['lib_id',Q(c.lib)],['at',fmt(x),fmt(y),str(c.rot)],['unit',str(c.unit)],['exclude_from_sim','no'],['in_bom','yes' if c.on_board or c.props.get('_bom','')=='yes' else 'no'],['on_board','yes' if c.on_board else 'no'],['dnp','yes' if c.dnp else 'no'],['uuid',Q(c.uuid)]]
    inst.append(P('Reference',ref,rpos[0],rpos[1],False,rpos[2]))
    inst.append(P('Value',c.value,vpos[0],vpos[1],False,vpos[2]))
    inst.append(P('Footprint',c.fp or prop(c.nick,c.name,'Footprint') or '',x,y,True))
    ds=prop(c.nick,c.name,'Datasheet') or ''
    inst.append(P('Datasheet',c.props.get('Datasheet',ds),x,y,True))
    inst.append(P('Description',c.desc or prop(c.nick,c.name,'Description') or '',x,y,True))
    for k,v in c.props.items():
        if k.startswith('_') or k=='Datasheet': continue
        inst.append(P(k,v,x,y,True))
    for p in c.pins:
        inst.append(['pin',Q(p['number']),['uuid',Q(U())]])
    inst.append(['instances',['project',Q(PROJECT),['path',Q(path),['reference',Q(ref)],['unit',str(c.unit)]]]])
    out.append(inst)
    # stubs and labels
    seen=set()
    for p in c.pins:
        net=c.pinmap.get(p['number'])
        X,Y=rot_vec(p['x'],p['y'],rot); px,py=x+X,y-Y
        d=out_dir(p,rot)
        key=(round(px,3),round(py,3),net)
        if key in seen: continue
        seen.add(key)
        if net is None: 
            print(f'  WARN unmapped pin {ref} {c.lib} pin {p["number"]} ({p["name"]}) -> NC')
            net='NC'
        if net=='NC':
            out.append(['no_connect',['at',fmt(px),fmt(py)],['uuid',Q(U())]]); continue
        ex,ey=px+d[0]*STUB,py+d[1]*STUB
        out.append(['wire',['pts',['xy',fmt(px),fmt(py)],['xy',fmt(ex),fmt(ey)]],['stroke',['width','0'],['type','solid']],['uuid',Q(U())]])
        if net=='GND':
            out.append(power_inst('GND',ex,ey,sheet,path,d))
        else:
            out.append(['global_label',Q(net),['shape','bidirectional'],['at',fmt(ex),fmt(ey),str(label_angle(d))],['fields_autoplaced','yes'],['effects',['font',['size','1.27','1.27']],['justify','left' if label_angle(d) in (0,90) else 'right']],['uuid',Q(U())],['property',Q('Intersheetrefs'),Q('${INTERSHEET_REFS}'),['at',fmt(ex),fmt(ey),'0'],['effects',['font',['size','1.27','1.27']],['hide','yes']]]])
    return out

