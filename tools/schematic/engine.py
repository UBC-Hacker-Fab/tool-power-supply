_pwr_counter=[0]
def power_inst(name,x,y,sheet,path,d):
    _pwr_counter[0]+=1
    ref=f'#PWR{_pwr_counter[0]:03d}'
    sheet.libs.add(('power',name))
    # GND symbol pin at origin; symbol drawn below origin when rot 0. choose rotation so it extends away from the stub
    rot={ (0,1):0, (1,0):90, (0,-1):180, (-1,0):270 }[d]
    inst=['symbol',['lib_id',Q('power:'+name)],['at',fmt(x),fmt(y),str(rot)],['unit','1'],['exclude_from_sim','no'],['in_bom','no'],['on_board','no'],['dnp','no'],['uuid',Q(U())],
      ['property',Q('Reference'),Q(ref),['at',fmt(x),fmt(y+3),'0'],['effects',['font',['size','1.27','1.27']],['hide','yes']]],
      ['property',Q('Value'),Q(name),['at',fmt(x),fmt(y+3.8),'0'],['effects',['font',['size','1.27','1.27']]]],
      ['property',Q('Footprint'),Q(''),['at',fmt(x),fmt(y),'0'],['effects',['font',['size','1.27','1.27']],['hide','yes']]],
      ['property',Q('Datasheet'),Q(''),['at',fmt(x),fmt(y),'0'],['effects',['font',['size','1.27','1.27']],['hide','yes']]],
      ['pin',Q('1'),['uuid',Q(U())]],
      ['instances',['project',Q(PROJECT),['path',Q(path),['reference',Q(ref)],['unit','1']]]]]
    return inst
